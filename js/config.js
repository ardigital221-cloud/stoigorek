function getMostFrequent(arr) {
  if (arr.length === 0) return "Нет данных";
  const counts = {};
  let maxCount = 0;
  let mostFrequent = arr[0];
  
  for (const item of arr) {
    if (!item) continue;
    counts[item] = (counts[item] || 0) + 1;
    if (counts[item] > maxCount) {
      maxCount = counts[item];
      mostFrequent = item;
    }
  }
  return mostFrequent;
}
